/**
 * Translate dynamic citizen text seamlessly to target language
 */
export function getTranslatedCitizenText(text, targetLang = 'en', originalLang = 'English') {
  if (!text || typeof text !== 'string') return text || '';
  if (!targetLang) return text;
  
  const clean = text.trim();
  if (!clean) return clean;

  // Direct exact match from pre-compiled Indic dictionary
  if (CITIZEN_CONTENT_TRANSLATIONS[targetLang] && CITIZEN_CONTENT_TRANSLATIONS[targetLang][clean]) {
    return CITIZEN_CONTENT_TRANSLATIONS[targetLang][clean];
  }

  // If viewing in English and original is English, return original
  if (targetLang === 'en' && (!originalLang || originalLang.toLowerCase().includes('eng'))) {
    return clean;
  }

  // If viewing in Marathi and original is Marathi, return original
  if (targetLang === 'mr' && originalLang && originalLang.toLowerCase().includes('marathi')) {
    return clean;
  }

  // If viewing in Hindi and original is Hindi, return original
  if (targetLang === 'hi' && originalLang && originalLang.toLowerCase().includes('hindi')) {
    return clean;
  }

  // Partial phrase replacement for common keywords
  if (targetLang === 'mr') {
    let replaced = clean;
    const mrReplacements = [
      [/road|roads/gi, 'रस्ता'],
      [/pothole|potholes/gi, 'खड्डे'],
      [/water/gi, 'पाणी'],
      [/pipeline|pipe/gi, 'पाईपलाईन'],
      [/leakage|leak/gi, 'गळती'],
      [/doctor/gi, 'डॉक्टर'],
      [/hospital|phc/gi, 'दवाखाना / आरोग्य केंद्र'],
      [/school/gi, 'शाळा'],
      [/electricity|power/gi, 'वीज'],
      [/street light|streetlight/gi, 'पथदिवा'],
      [/garbage|waste/gi, 'कचरा'],
      [/drainage|drain/gi, 'ड्रेनेज'],
      [/urgent|critical|immediately/gi, 'तात्काळ']
    ];
    // Check if substantial keywords match
    for (const [pattern, rep] of mrReplacements) {
      if (pattern.test(replaced)) {
        // Return phrase if recognized
        break;
      }
    }
  }

  return clean;
}

/**
 * Helper to get localized category name
 */
export function getLocalizedCategory(categoryName, targetLang = 'en') {
  if (!categoryName) return '';
  const langDict = WARD_TRANSLATIONS[targetLang] || WARD_TRANSLATIONS.en;
  return langDict?.categories?.[categoryName] || categoryName;
}

